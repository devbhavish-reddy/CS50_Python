# Conditionals in python

"""
* Conditional in python is a checklist/comparison between two variables.

A conditional statement controls the flow of execution in a program by running
specific blocks of code based on whether a condition is true or false.

"""



"""

1. If condition.

* The "If Condition" is a checker/approver to only execute a block of code only and 
only if the boolean condition is true. 

2. Elif condition

* Short for else-if, this condition acts as a parallel pathway when the boolean expression 
under the if conditions is false. Essientaly this is another if condition, but only 
comes after the if condition.


3. Else condition

* The else condition is always written at the end of the sequence, usually the conditional
has no boolean expression. This checkmark always acts true. 




"""


# If condition
name = input("What is your name? ")
name_org = "Harry"


if name == name_org:
    print("Hello Harry")

#Elif condition

number = float(input("Enter your number: "))

if number > 0:
    print("Positive")

elif number < 0:
    print("Negative")

# Else

age = int(input("Enter your age: "))
if age >= 18:
    print("Go vote!")

else:
    print("Cannot vote..")# Conditionals in python

